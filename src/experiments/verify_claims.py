"""Recompute every cross-culture claim from the raw per-subject results.

Each claim family is tested per test subject (accuracy averaged over seeds
first, so subjects are the unit of analysis):

  A  normalisation gain: <model>__subjnorm vs <model>, per setting
  B  our fair normalised results vs the paper's single reported number
     (bootstrap CI of our mean; NOT like-for-like, reported as context)
  C  leakage: test-selected C (oracle) vs source-CV C, on the paper's SVM
  D  4 s vs 1 s windows (normalised MLP)
  E  self-training (mlp_st) vs normalised MLP
  F  class-conditional SCVAE vs the best normalised baseline
  G  within-culture SCVAE vs the normalised SVM and MLP

Paired families report the mean difference, a 95% bootstrap CI, wins, a
two-sided Wilcoxon signed-rank p and a Holm-adjusted p within the family.
With 8-12 subjects per setting, tests have little power; a non-significant
difference is not evidence of no difference.

    python -m src.experiments.verify_claims   # -> results/tables/verification_report.md
"""

import argparse
import json
from collections import defaultdict
from pathlib import Path

import numpy as np
from scipy.stats import wilcoxon

from src.experiments.summarize_crossculture import PAPER


CULTURES = ["SEED_CHN_MM", "SEED_GER", "SEED_FRA"]
NAMES = {"SEED_CHN_MM": "Chinese", "SEED_GER": "German", "SEED_FRA": "French"}
PAPER_NAME = {"SEED_CHN_MM": "SEED_CHN"}
RNG = np.random.default_rng(0)


def settings():
    for target in CULTURES:
        for source in CULTURES:
            yield source, target


def suffix(source, target):
    return "pooled" if source == target else f"from_{source}"


def load(run_dir):
    """test subject -> accuracy averaged over seeds (None if the run is missing)."""
    per_subject = defaultdict(list)
    for path in Path(run_dir).glob("session_all/seed_*/subject_*.json"):
        record = json.loads(path.read_text())
        per_subject[record["test_subject"]].append(record["accuracy"])
    return {s: 100 * float(np.mean(v)) for s, v in per_subject.items()} or None


def bootstrap_ci(values, n=10000):
    values = np.asarray(values)
    means = RNG.choice(values, size=(n, len(values)), replace=True).mean(axis=1)
    return np.percentile(means, [2.5, 97.5])


def paired(a, b):
    subjects = sorted(set(a) & set(b))
    diff = np.array([a[s] - b[s] for s in subjects])
    p = wilcoxon(diff).pvalue if np.any(diff != 0) and len(diff) >= 5 else 1.0
    lo, hi = bootstrap_ci(diff)
    return {"n": len(diff), "mean": diff.mean(), "lo": lo, "hi": hi, "wins": int((diff > 0).sum()), "p": p}


def holm(rows):
    order = np.argsort([r["p"] for r in rows])
    m, running = len(rows), 0.0
    for rank, i in enumerate(order):
        running = max(running, min(1.0, (m - rank) * rows[i]["p"]))
        rows[i]["p_holm"] = running
    return rows


def fmt_paired(title, rows):
    out = [f"### {title}", "",
           "| Comparison | n | Mean diff (pts) | 95% CI | Wins | p | p (Holm) |",
           "|---|---:|---:|---|---:|---:|---:|"]
    for r in holm(rows):
        out.append(f"| {r['label']} | {r['n']} | {r['mean']:+.1f} | [{r['lo']:+.1f}, {r['hi']:+.1f}] | "
                   f"{r['wins']}/{r['n']} | {r['p']:.3f} | {r['p_holm']:.3f} |")
    return out + [""]


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--root", type=Path, default=Path("results/crossculture"))
    parser.add_argument("--scvae-root", type=Path, default=Path("results/scvae_fix/ep30"))
    parser.add_argument("--within-scvae-root", type=Path, default=Path("results/crossculture_scvae"))
    parser.add_argument("--output", type=Path, default=Path("results/tables/verification_report.md"))
    args = parser.parse_args()
    report = ["# Verification report", "",
              "Generated by `python -m src.experiments.verify_claims` from the raw per-subject results. "
              "Unit of analysis: test subject (seeds averaged). Two-sided Wilcoxon signed-rank tests; "
              "Holm correction within each table. 95% CIs by bootstrap over subjects.", ""]

    # A. normalisation gain
    rows = []
    for model in ["svm", "linsvm", "mlp"]:
        for source, target in settings():
            a = load(args.root / target / f"{model}__subjnorm__{suffix(source, target)}")
            b = load(args.root / target / f"{model}__{suffix(source, target)}")
            if a and b:
                rows.append({"label": f"{model}: {NAMES[source]} → {NAMES[target]}", **paired(a, b)})
    report += fmt_paired("A. Normalisation gain (normalised minus unnormalised, 4 s)", rows)
    gains = [r["mean"] for r in rows]
    report += [f"Range of mean gains: {min(gains):+.1f} to {max(gains):+.1f} points; "
               f"{sum(r['p_holm'] < 0.05 for r in rows)}/{len(rows)} significant after Holm.", ""]

    # B. fair normalised results vs paper
    report += ["### B. Best fair normalised model vs the paper's reported number (context only, not like-for-like)", "",
               "| Setting | Best normalised model | Our mean | 95% CI | Paper SVM | Paper DNN | CI above paper SVM? | CI above paper DNN? |",
               "|---|---|---:|---|---:|---:|---|---|"]
    for source, target in settings():
        best = None
        for model in ["svm", "linsvm", "mlp"]:
            a = load(args.root / target / f"{model}__subjnorm__{suffix(source, target)}")
            if a and (best is None or np.mean(list(a.values())) > np.mean(list(best[1].values()))):
                best = (model, a)
        if best is None:
            continue
        vals = list(best[1].values())
        lo, hi = bootstrap_ci(vals)
        key = (PAPER_NAME.get(source, source), PAPER_NAME.get(target, target))
        ps, pd = PAPER["svm"][key], PAPER["dnn"][key]
        report.append(f"| {NAMES[source]} → {NAMES[target]} | {best[0]} | {np.mean(vals):.1f} | [{lo:.1f}, {hi:.1f}] | "
                      f"{ps} | {pd} | {'yes' if lo > ps else 'no'} | {'yes' if lo > pd else 'no'} |")
    report += ["", "Picking the best of three models per setting is itself a (small) selection effect; "
               "the paper used 1 s windows and an unconfirmed selection procedure.", ""]

    # C. leakage
    audit_path = args.root / "liu_leakage_audit.json"
    if audit_path.exists():
        audit = json.loads(audit_path.read_text())
        rows = []
        for key, folds in audit.items():
            oracle = {int(s): 100 * f["oracle"] for s, f in folds.items()}
            fair = {int(s): 100 * f["source_cv"] for s, f in folds.items()}
            src, tgt = key.split("->")
            rows.append({"label": f"{NAMES.get(src, src)} → {NAMES.get(tgt, tgt)}", **paired(oracle, fair)})
        report += fmt_paired("C. Leakage: test-selected C minus source-CV C (approximate Liu et al. linear SVM, 4 s, coarse grid)", rows)
        report += ["By construction the test-selected C can never be worse, so a positive difference is guaranteed; "
                   "the question is its size. This audit approximates the paper's setup (4 s windows, coarse C grid only).", ""]

    # D. 4 s vs 1 s
    rows = []
    for source, target in settings():
        a = load(args.root / target / f"mlp__subjnorm__{suffix(source, target)}")
        b = load(args.root / f"{target}_1s" / f"mlp__subjnorm__{suffix(source, target)}_1s".replace("pooled_1s", "pooled"))
        if a and b:
            rows.append({"label": f"{NAMES[source]} → {NAMES[target]}", **paired(a, b)})
    report += fmt_paired("D. Window length: normalised MLP, 4 s minus 1 s", rows)

    # E. self-training
    rows = []
    for source, target in settings():
        a = load(args.root / target / f"mlp_st__subjnorm__{suffix(source, target)}")
        b = load(args.root / target / f"mlp__subjnorm__{suffix(source, target)}")
        if a and b:
            rows.append({"label": f"{NAMES[source]} → {NAMES[target]}", **paired(a, b)})
    report += fmt_paired("E. Self-training (mlp_st) minus normalised MLP", rows)

    # F. class-conditional SCVAE vs best normalised baseline (per setting, best by mean)
    rows = []
    for source, target in settings():
        if source == target:
            continue
        a = load(args.scvae_root / target /
                 f"strict__class_conditional_mmd__bn_source__tshuf__subjnorm__from_{source}")
        best = None
        for model in ["svm", "linsvm", "mlp"]:
            b = load(args.root / target / f"{model}__subjnorm__from_{source}")
            if b and (best is None or np.mean(list(b.values())) > np.mean(list(best.values()))):
                best = b
        if a and best:
            rows.append({"label": f"{NAMES[source]} → {NAMES[target]}", **paired(a, best)})
    report += fmt_paired("F. Class-conditional SCVAE (1 seed) minus best normalised baseline", rows)

    # G. within-culture SCVAE vs normalised baselines
    rows = []
    for target in CULTURES:
        for run, label in [("strict__bn_source__pooled", "SCVAE BN fix"),
                           ("strict__bn_source__subjnorm__pooled", "SCVAE BN fix + norm"),
                           ("strict__bn_target__subjnorm__pooled", "SCVAE subject BN + norm")]:
            a = load(args.within_scvae_root / target / run)
            if not a:
                continue
            for model in ["svm", "mlp"]:
                b = load(args.root / target / f"{model}__subjnorm__pooled")
                if b:
                    rows.append({"label": f"{NAMES[target]}: {label} vs {model} norm", **paired(a, b)})
    report += fmt_paired("G. Within-culture SCVAE (1 seed) minus normalised baselines", rows)

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(report) + "\n")
    print("\n".join(report))


if __name__ == "__main__":
    main()
