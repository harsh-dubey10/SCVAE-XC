"""Compare EEG, eye-movement and EEG+eye baselines across cultures, per test subject.

Reads the strict baseline runs in ``results/crossculture/<culture><suffix>/``
(suffix "" for EEG, "_EYE", "_EEG_EYE"; 4 s windows) and reports, with
subjects as the unit of analysis (seeds averaged first):

  M  accuracy of every normalised model, per modality and setting
  N  normalisation gain for the eye and EEG+eye features
  O  eye minus EEG (normalised, same model)
  P  EEG+eye minus EEG (normalised, same model)
  Q  EEG+eye minus eye (normalised, same model)
  R  transfer drop: (within - cross) for eye minus (within - cross) for EEG,
     per target subject; positive means eye features lose more across cultures

Paired families use the same statistics as verify_claims: mean difference,
95% bootstrap CI, wins, two-sided Wilcoxon p and Holm-adjusted p per table.

    python -m src.experiments.compare_modalities   # -> results/tables/modality_report.md
"""

import argparse
from pathlib import Path

import numpy as np

from src.experiments.verify_claims import CULTURES, NAMES, bootstrap_ci, fmt_paired, load, paired, settings, suffix


MODALITIES = {"eeg": "", "eye": "_EYE", "eeg+eye": "_EEG_EYE"}
MODELS = ["svm", "linsvm", "mlp"]


def run(root, modality, model, source, target, norm=True):
    folder = root / f"{target}{MODALITIES[modality]}"
    source_name = f"{source}{MODALITIES[modality]}"
    tail = "pooled" if source == target else f"from_{source_name}"
    return load(folder / f"{model}{'__subjnorm' if norm else ''}__{tail}")


def label(source, target):
    return f"{NAMES[source]} → {NAMES[target]}"


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--root", type=Path, default=Path("results/crossculture"))
    parser.add_argument("--output", type=Path, default=Path("results/tables/modality_report.md"))
    args = parser.parse_args()
    report = ["# Modality report: EEG vs eye movements vs EEG+eye", "",
              "Generated by `python -m src.experiments.compare_modalities` from the raw per-subject results "
              "(strict protocol, 4 s windows). Unit of analysis: test subject (seeds averaged). Two-sided Wilcoxon "
              "signed-rank tests; Holm correction within each table. 95% CIs by bootstrap over subjects. "
              "\"Normalised\" = each recording standardised with its own statistics (label-free).", ""]

    # M. accuracy table
    header = " | ".join(f"{m} {mod}" for mod in MODALITIES for m in MODELS)
    report += ["### M. Accuracy (%) of normalised models, mean over test subjects", "",
               f"| Setting | {header} |", "|---|" + "---:|" * (len(MODELS) * len(MODALITIES))]
    for source, target in settings():
        cells = []
        for modality in MODALITIES:
            for model in MODELS:
                a = run(args.root, modality, model, source, target)
                cells.append(f"{np.mean(list(a.values())):.1f}" if a else "—")
        report.append(f"| {label(source, target)} | " + " | ".join(cells) + " |")
    report += [""]

    # N. normalisation gain on the new modalities
    rows = []
    for modality in ["eye", "eeg+eye"]:
        for model in MODELS:
            for source, target in settings():
                a = run(args.root, modality, model, source, target)
                b = run(args.root, modality, model, source, target, norm=False)
                if a and b:
                    rows.append({"label": f"{modality} {model}: {label(source, target)}", **paired(a, b)})
    report += fmt_paired("N. Normalisation gain (normalised minus unnormalised), eye and EEG+eye", rows)
    gains = [r["mean"] for r in rows]
    report += [f"Mean gain positive in {sum(g > 0 for g in gains)}/{len(gains)}, range {min(gains):+.1f} to "
               f"{max(gains):+.1f} points; 95% CI above zero in {sum(r['lo'] > 0 for r in rows)}/{len(rows)}; "
               f"{sum(r['p_holm'] < 0.05 for r in rows)}/{len(rows)} significant after Holm.", ""]

    # O-Q. modality differences under normalisation
    for key, (a_mod, b_mod) in {"O": ("eye", "eeg"), "P": ("eeg+eye", "eeg"), "Q": ("eeg+eye", "eye")}.items():
        rows = []
        for model in MODELS:
            for source, target in settings():
                a = run(args.root, a_mod, model, source, target)
                b = run(args.root, b_mod, model, source, target)
                if a and b:
                    rows.append({"label": f"{model}: {label(source, target)}", "within": source == target,
                                 **paired(a, b)})
        report += fmt_paired(f"{key}. {a_mod} minus {b_mod} (normalised, same model)", rows)
        for name, part in [("within", [r for r in rows if r["within"]]),
                           ("cross", [r for r in rows if not r["within"]])]:
            if part:
                report.append(f"{name}: {a_mod} ahead in {sum(r['mean'] > 0 for r in part)}/{len(part)} "
                              f"(mean of means {np.mean([r['mean'] for r in part]):+.1f} points; "
                              f"CI above zero in {sum(r['lo'] > 0 for r in part)}, below zero in "
                              f"{sum(r['hi'] < 0 for r in part)}).")
        report += [""]

    # R. transfer drop, eye vs EEG
    rows = []
    for model in MODELS:
        for source, target in settings():
            if source == target:
                continue
            runs = {mod: (run(args.root, mod, model, target, target), run(args.root, mod, model, source, target))
                    for mod in ["eye", "eeg"]}
            if not all(w and c for w, c in runs.values()):
                continue
            drop = {mod: {s: w[s] - c[s] for s in set(w) & set(c)} for mod, (w, c) in runs.items()}
            rows.append({"label": f"{model}: {label(source, target)}", **paired(drop["eye"], drop["eeg"])})
    report += fmt_paired("R. Transfer drop (within minus cross), eye minus EEG (normalised); "
                         "positive = eye loses more across cultures", rows)
    report += [f"Eye drops more in {sum(r['mean'] > 0 for r in rows)}/{len(rows)} model × setting pairs "
               f"(mean of means {np.mean([r['mean'] for r in rows]):+.1f} points).", ""]

    # Overall: best normalised model per modality, with CI (context; picking the best is a small selection effect)
    report += ["### S. Best normalised model per modality (selection over 3 models; context only)", "",
               "| Setting | EEG | eye | EEG+eye |", "|---|---|---|---|"]
    for source, target in settings():
        cells = []
        for modality in MODALITIES:
            best = max((a for a in (run(args.root, modality, m, source, target) for m in MODELS) if a),
                       key=lambda a: np.mean(list(a.values())), default=None)
            if best:
                lo, hi = bootstrap_ci(list(best.values()))
                cells.append(f"{np.mean(list(best.values())):.1f} [{lo:.1f}, {hi:.1f}]")
            else:
                cells.append("—")
        report.append(f"| {label(source, target)} | " + " | ".join(cells) + " |")
    report += [""]

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(report) + "\n")
    print("\n".join(report))


if __name__ == "__main__":
    main()
